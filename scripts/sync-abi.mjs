// Copies the compiled contract ABIs into the app so the two never drift.
// Run after `forge build`: node scripts/sync-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

for (const [contract, file, name] of [
  ["StandIn", "standin-abi.ts", "standInAbi"],
  ["ProofOfMet", "met-abi.ts", "metAbi"],
]) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${contract}.sol/${contract}.json`), "utf8"));
  const out = join(root, "app/src/lib", file);
  writeFileSync(
    out,
    `// Generated by scripts/sync-abi.mjs from contracts/out/${contract}.sol/${contract}.json. Do not edit.\n` +
      `export const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  console.log(`wrote ${out} (${artifact.abi.length} entries)`);
}
